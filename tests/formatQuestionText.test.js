// Срез бланковых хвостов ФИПИ при показе вопроса (formatQuestionText).
// data.js не правим — только отображение.

import { describe, it, expect } from "vitest";
import { formatQuestionText } from "../src/pages/Trainer.jsx";

describe("formatQuestionText — бланковые хвосты после ?", () => {
  it("Катрина: срезает « океан» после вопроса", () => {
    const q =
      "Над акваторией какого океана возник ураган, о котором говорится в тексте? океан";
    expect(formatQuestionText(q)).toBe(
      "Над акваторией какого океана возник ураган, о котором говорится в тексте?",
    );
  });

  it("срезает географические и админ. ярлыки из whitelist", () => {
    const cases = [
      ["…? море", "…?"],
      ["…? край", "…?"],
      ["…? область", "…?"],
      ["…? Республика", "…?"],
      ["…? горы", "…?"],
      ["…? залив", "…?"],
      ["…? низменность", "…?"],
      ["…? возвышенность", "…?"],
      ["…? магистраль", "…?"],
      ["…? автономный округ", "…?"],
    ];
    for (const [input, want] of cases) {
      expect(formatQuestionText(input)).toBe(want);
    }
  });

  it("не трогает вопрос без бланкового хвоста", () => {
    const q = "Какой океан омывает восточное побережье Африки?";
    expect(formatQuestionText(q)).toBe(q);
  });

  it("не срезает слово из whitelist, если оно не сразу после ?", () => {
    const q = "Укажите океан, в котором возник ураган.";
    expect(formatQuestionText(q)).toBe(q);
  });
});

describe("formatQuestionText — бланковый хвост «. %»", () => {
  it("срезает единицу % после инструкции округления", () => {
    const q =
      "Определите долю населения. Полученный результат округлите до целого числа. %";
    expect(formatQuestionText(q)).toBe(
      "Определите долю населения. Полученный результат округлите до целого числа.",
    );
  });

  it("не срезает % из таблицы (после цифр, без точки)", () => {
    const q = "Поступило на переработку 290,7 Экспорт 2 60 , 2 %";
    expect(formatQuestionText(q)).toBe(q);
  });
});
